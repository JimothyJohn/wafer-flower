// BEVELOID gear (2026-07-25, generated, parallel axes): the teeth live on
// a 45-deg cone — big end at the WALL, working face toward the viewer —
// meshing a module-matched complementary-coned
// pinion on an AXIAL axis above the ring at 12 o'clock (motor pointing
// out of the wall). Tooth count MUST divide by N or the pattern breaks at
// the joints. The REAL teeth are generated by CSG in segment_stl.py; this
// page draws the coned band with a schematic tooth wave.
function gearSpec(){
  // EXTERNAL bevel (2026-07-25): teeth on a web OUTSIDE the band, big end
  // at the wafer side, pinion above the ring on the wall bracket
  const Ro=P.Ri+P.bw;
  const target=Ro+1.25*GEAR_M+2;
  const tps=Math.max(6,Math.ceil(2*target/GEAR_M/P.N)); // teeth per segment — floor MUST match Cfg's max(6,...) or the page draws a gear the generator never builds
  const T=tps*P.N;
  // FLUSH module: tooth count is quantised in steps of N, so the module is
  // retuned to land the FRONT root circle 1 mm inside the band OD — the
  // teeth rise straight off the band wall (5.6 nominal -> 5.384 at B.3)
  const me=(Ro-1)/(T/2-1.25), rp=T*me/2;
  const kb=(rp+GEAR_F)/rp;   // cone scale at the WALL (big end at the wall)
  return {tps:tps, T:T, rp:rp, tip:rp+me, root:rp-1.25*me,
          tip_front:(rp+me)*kb, kb:kb, web_i:Ro-2, m:me};
}
// schematic tooth boundary at the cone FRONT (wafer side); the wall layer
// scales it by (tip+GEAR_F)/tip for the 45-deg lean
function toothWave(a,g){
  const pitch=2*Math.PI/g.T, ph=((a%pitch)+pitch)%pitch, f=ph/pitch;
  if(f<0.08) return g.root+(g.tip-g.root)*(f/0.08);
  if(f<0.46) return g.tip;
  if(f<0.54) return g.tip+(g.root-g.tip)*((f-0.46)/0.08);
  return g.root;
}

