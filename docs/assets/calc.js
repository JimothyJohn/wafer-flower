function arcStrip(cx,cy,r0,r1,a0,a1,z0,z1,color,n){
  // annular wall band about (cx,cy), angles a0..a1, z0..z1
  const pos=[],idx=[],q=(a,b,c,d)=>{idx.push(a,b,c,a,c,d);};
  n=n||24;
  for(let j=0;j<=n;j++){
    const a=a0+(a1-a0)*j/n, c=Math.cos(a), s=Math.sin(a);
    pos.push(cx+r0*c,cy+r0*s,z1, cx+r1*c,cy+r1*s,z1,
             cx+r0*c,cy+r0*s,z0, cx+r1*c,cy+r1*s,z0);
  }
  for(let j=0;j<n;j++){
    const A=j*4,B=(j+1)*4;
    q(A,A+1,B+1,B); q(A+3,A+2,B+2,B+3); q(A+2,A,B,B+2); q(A+1,A+3,B+3,B+1);
  }
  const g=new THREE.BufferGeometry();
  g.setAttribute('position',new THREE.Float32BufferAttribute(pos,3));
  g.setIndex(idx); g.computeVertexNormals();
  return new THREE.Mesh(g,new THREE.MeshPhongMaterial({color:color,shininess:16,side:THREE.DoubleSide}));
}
