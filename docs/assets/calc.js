// BEVEL45 gear (2026-07-24, generated): the teeth live on a 45-deg cone —
// tips start at r = pitch - m on the wafer side and drop radially outward
// by tmin toward the mounting wall — meshing a module-matched 45-deg coned
// pinion on a radial axis behind the ring (motor flat against the wall,
// perpendicular). Tooth count MUST divide by N or the pattern breaks at
// the joints. The REAL teeth are generated by CSG in segment_stl.py; this
// page draws the coned band with a schematic tooth wave.
function gearSpec(){
  const target=P.Ri-5;
  const tps=Math.max(8,Math.round(2*target/GEAR_M/P.N)); // teeth per segment, integer
  const T=tps*P.N, rp=T*GEAR_M/2;
  const tip=rp-GEAR_M;                                   // cone small end, wafer side
  return {tps:tps, T:T, rp:rp, tip:tip, tip_wall:tip+P.tmin,
          band_o:tip+16, m:GEAR_M};
}
// schematic tooth boundary at the cone FRONT (wafer side); the wall layer
// scales it by (tip+tmin)/tip for the 45-deg lean
function toothWave(a,g){
  const pitch=2*Math.PI/g.T, ph=((a%pitch)+pitch)%pitch, f=ph/pitch;
  const root=g.rp+1.25*GEAR_M;
  if(f<0.08) return root+(g.tip-root)*(f/0.08);
  if(f<0.46) return g.tip;
  if(f<0.54) return g.tip+(root-g.tip)*((f-0.46)/0.08);
  return root;
}

